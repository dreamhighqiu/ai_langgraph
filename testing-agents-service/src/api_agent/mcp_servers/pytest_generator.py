    # 函数定义
    lines.append(f'def {func_name}(api_client):')
    lines.append(f'    """')
    lines.append(f'    {test_case.description or test_case.name}')
    if test_case.preconditions:
        lines.append(f'    ')
        lines.append(f'    Preconditions:')
        for pre in test_case.preconditions:
            lines.append(f'    - {pre}')
    lines.append(f'    """')
    
    # Setup步骤
    if test_case.setup_steps:
        lines.append('    # Setup')
        for step in test_case.setup_steps:
            lines.append(_generate_step_code(step, "    "))
    
    # 主测试步骤
    lines.append('    # Test Steps')
    for step in test_case.steps:
        lines.append(_generate_step_code(step, "    "))
    
    # Teardown步骤
    if test_case.teardown_steps:
        lines.append('    # Teardown')
        for step in test_case.teardown_steps:
            lines.append(_generate_step_code(step, "    "))

    return "\n".join(lines)


