@mcp.tool()
async def generate_pytest_ini(
    output_dir: Optional[str] = None,
    markers: Optional[list[str]] = None,
    ctx: Context = None
) -> str:
    """
    生成pytest.ini配置文件

    参数：
        output_dir: 输出目录（可选）
        markers: 自定义markers列表（可选）

    返回：
        生成结果的JSON字符串
    """
    try:
        context = ctx.request_context.lifespan_context
        out_dir = output_dir or context.output_dir
        os.makedirs(out_dir, exist_ok=True)

        default_markers = [
            "critical: 关键测试",
            "high: 高优先级测试",
            "medium: 中优先级测试",
            "low: 低优先级测试",
            "smoke: 冒烟测试",
            "regression: 回归测试",
            "integration: 集成测试"
        ]

        all_markers = default_markers + (markers or [])

        content = f'''[pytest]
testpaths = tests
python_files = test_*.py
python_classes = Test*
python_functions = test_*
addopts = -v --tb=short --alluredir=./allure-results
markers =
    {chr(10).join("    " + m for m in all_markers)}
'''

        file_path = os.path.join(out_dir, "pytest.ini")
        with open(file_path, 'w', encoding='utf-8') as f:
            f.write(content)

        return GenerationResult(
            success=True,
            message="成功生成pytest.ini",
            files=[GeneratedTestFile(
                file_path=file_path,
                file_name="pytest.ini",
                content=content,
                language="ini",
                framework="pytest"
            )]
        ).model_dump_json(indent=2)

    except Exception as e:
        return GenerationResult(
            success=False,
            message=f"生成失败: {str(e)}",
            errors=[str(e)]
        ).model_dump_json(indent=2)


