@mcp.tool()
async def generate_pytest_tests(
    test_suite_json: str,
    output_dir: Optional[str] = None,
    ctx: Context = None
) -> str:
    """
    从测试套件生成pytest测试文件

    参数：
        test_suite_json: TestSuite的JSON字符串
        output_dir: 输出目录（可选）

    返回：
        生成结果的JSON字符串
    """
    try:
        suite_data = json.loads(test_suite_json)
        test_suite = TestSuite(**suite_data)

        context = ctx.request_context.lifespan_context
        out_dir = output_dir or context.output_dir
        os.makedirs(out_dir, exist_ok=True)

        generated_files = []
        timestamp = datetime.now().isoformat()

        file_name = f"test_{_sanitize_name(test_suite.name)}.py"
        file_path = os.path.join(out_dir, file_name)

        content_lines = [
            PYTEST_IMPORTS_TEMPLATE.format(
                description=f"API测试: {test_suite.name}",
                timestamp=timestamp
            )
        ]

        content_lines.append(f'\n@allure.feature("{test_suite.name}")')
        content_lines.append(f'class Test{_sanitize_name(test_suite.name).title().replace("_", "")}:')
        content_lines.append(f'    """{test_suite.description or test_suite.name}"""')
        content_lines.append('')

        for test_case in test_suite.test_cases:
            case_code = _generate_test_case_code(test_case)
            indented_code = "\n".join("    " + line if line.strip() else line
                                      for line in case_code.split("\n"))
            content_lines.append(indented_code)
            content_lines.append('')

        content = "\n".join(content_lines)

        with open(file_path, 'w', encoding='utf-8') as f:
            f.write(content)

        generated_files.append(GeneratedTestFile(
            file_path=file_path,
            file_name=file_name,
            content=content,
            language="python",
            framework="pytest"
        ))

        result = GenerationResult(
            success=True,
            message=f"成功生成 {len(generated_files)} 个测试文件",
            files=generated_files
        )
# pragma: no cover  My80OmFIVnBZMlhwZ3JIa3VwSHBuSjQ2UlhGQk1nPT06MzJlMTFlZTk=

        return result.model_dump_json(indent=2)

    except Exception as e:
        result = GenerationResult(
            success=False,
            message=f"生成失败: {str(e)}",
            errors=[str(e)]
        )
        return result.model_dump_json(indent=2)


