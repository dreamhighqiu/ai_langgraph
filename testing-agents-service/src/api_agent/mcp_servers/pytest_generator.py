def _get_priority_marker(priority: TestPriority) -> str:
    """获取优先级对应的pytest marker"""
    markers = {
        TestPriority.CRITICAL: '@pytest.mark.critical',
        TestPriority.HIGH: '@pytest.mark.high',
        TestPriority.MEDIUM: '@pytest.mark.medium',
        TestPriority.LOW: '@pytest.mark.low'
    }
    return markers.get(priority, '@pytest.mark.medium')


def _get_allure_severity(priority: TestPriority) -> str:
    """获取优先级对应的Allure severity"""
    severity_map = {
        TestPriority.CRITICAL: 'allure.severity_level.CRITICAL',
        TestPriority.HIGH: 'allure.severity_level.NORMAL',
        TestPriority.MEDIUM: 'allure.severity_level.MINOR',
        TestPriority.LOW: 'allure.severity_level.TRIVIAL'
    }
    return severity_map.get(priority, 'allure.severity_level.NORMAL')


def _generate_step_code(step: TestStep, indent: str = "    ") -> str:
    """生成测试步骤代码"""
    lines = []
    
    # 添加allure步骤装饰
    lines.append(f'{indent}with allure.step("{step.name}"):')
    step_indent = indent + "    "
    
    # 构建请求参数
    method = step.method.value.lower()
    endpoint = step.endpoint
    
    # 处理路径参数
    for param_name, param_value in step.path_params.items():
        endpoint = endpoint.replace(f"{{{param_name}}}", str(param_value))
    
    # 构建请求调用
    request_args = []
    if step.query_params:
        request_args.append(f"params={json.dumps(step.query_params)}")
    if step.headers:
        request_args.append(f"headers={json.dumps(step.headers)}")
    if step.request_body:
        request_args.append(f"json={json.dumps(step.request_body)}")
    
    args_str = ", ".join(request_args)
    if args_str:
        lines.append(f'{step_indent}response = api_client.{method}("{endpoint}", {args_str})')
    else:
        lines.append(f'{step_indent}response = api_client.{method}("{endpoint}")')
    
    # 生成断言
    for assertion in step.assertions:
        if assertion.assertion_type == "status_code":
            lines.append(f'{step_indent}assert response.status_code == {assertion.expected_value}, '
                        f'f"Expected status {assertion.expected_value}, got {{response.status_code}}"')
        elif assertion.assertion_type == "json_path":
            lines.append(f'{step_indent}response_json = response.json()')
            lines.append(f'{step_indent}# TODO: 验证JSON路径 {assertion.actual_path}')
        elif assertion.assertion_type == "response_time":
            lines.append(f'{step_indent}assert response.elapsed.total_seconds() * 1000 < {assertion.expected_value}, '
                        f'"Response time exceeded {assertion.expected_value}ms"')
    
    # 提取变量
    if step.extract_variables:
        lines.append(f'{step_indent}response_json = response.json()')
        for var_name, json_path in step.extract_variables.items():
            lines.append(f'{step_indent}# 提取变量: {var_name} from {json_path}')
    
    return "\n".join(lines)


def _generate_test_case_code(test_case: TestCase) -> str:
    """生成单个测试用例代码"""
    func_name = f"test_{_sanitize_name(test_case.name)}"
    
    lines = []
    
    # 添加allure装饰器
    lines.append(f'@allure.title("{test_case.name}")')
    lines.append(f'@allure.description("""{test_case.description}""")')
    lines.append(f'@allure.severity({_get_allure_severity(test_case.priority)})')
    
    # 添加标签
    for tag in test_case.tags:
        lines.append(f'@allure.tag("{tag}")')
    
    # 添加优先级marker
    lines.append(_get_priority_marker(test_case.priority))
